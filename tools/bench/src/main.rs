#[derive(Clone)]
struct Row {
    category: String,
    name: String,
    mean_ns: f64,
    median_ns: f64,
    p95_ns: f64,
    min_ns: f64,
    max_ns: f64,
    stddev_ns: f64,
    ops_per_sec: f64,
    samples: usize,
    inner: u64,
}

struct Config {
    csv: bool,
    quick: bool,
    no_header: bool,
    filter: Option<String>,
}

fn main() {
    let config = parse_args();
    let samples = if config.quick { 5 } else { 25 };
    let target_ms = if config.quick { 20.0 } else { 40.0 };

    if !config.csv && !config.no_header {
        println!("# VORB3 SP-288/35 full benchmark");
        println!();
        println!("Generated by `tools/bench` (std-only custom harness).");
        println!();
        println!("- arch: `{}`", std::env::consts::ARCH);
        println!("- os: `{}`", std::env::consts::OS);
        println!("- cpu: {}", cpu_model());
        println!("- samples per benchmark: {samples}");
        println!("- target time per sample: {target_ms:.0} ms");
        println!("- `inner` is the auto-calibrated loop count per sample");
        println!();
        println!(
            "| Category | Benchmark | Mean ns/op | Median ns/op | p95 ns/op | Min ns/op | Max ns/op | Stddev ns | Ops/s | Samples | Inner |"
        );
        println!("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
    } else if config.csv {
        println!(
            "category,benchmark,mean_ns,median_ns,p95_ns,min_ns,max_ns,stddev_ns,ops_per_sec,samples,inner"
        );
    }

    let mut runner = Runner {
        config: &config,
        samples,
        target_ms,
    };

    setup_and_run(&mut runner);
    println!();
    println!("Max RSS: {} MiB", max_rss_kb() / 1024);
}

fn parse_args() -> Config {
    let mut config = Config {
        csv: false,
        quick: false,
        no_header: false,
        filter: None,
    };
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut index = 0;
    while index < args.len() {
        match args[index].as_str() {
            "--csv" => config.csv = true,
            "--quick" => config.quick = true,
            "--no-header" => config.no_header = true,
            "--filter" => {
                index += 1;
                config.filter = args.get(index).cloned();
            }
            "--help" | "-h" => {
                println!("usage: vorb3-bench [--csv] [--quick] [--no-header] [--filter SUBSTR]");
                std::process::exit(0);
            }
            other => {
                eprintln!("unknown argument: {other}");
                std::process::exit(2);
            }
        }
        index += 1;
    }
    config
}

struct Runner<'a> {
    config: &'a Config,
    samples: usize,
    target_ms: f64,
}

impl Runner<'_> {
    fn run<T, F>(&mut self, category: &str, name: &str, mut work: F)
    where
        F: FnMut() -> T,
    {
        if let Some(filter) = &self.config.filter
            && !category.contains(filter)
            && !name.contains(filter)
        {
            return;
        }
        let row = measure(category, name, self.samples, self.target_ms, &mut work);
        if self.config.csv {
            println!(
                "{},{},{:.3},{:.3},{:.3},{:.3},{:.3},{:.3},{:.3},{},{}",
                row.category,
                row.name,
                row.mean_ns,
                row.median_ns,
                row.p95_ns,
                row.min_ns,
                row.max_ns,
                row.stddev_ns,
                row.ops_per_sec,
                row.samples,
                row.inner
            );
        } else {
            println!(
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                row.category,
                row.name,
                display_value(row.mean_ns),
                display_value(row.median_ns),
                display_value(row.p95_ns),
                display_value(row.min_ns),
                display_value(row.max_ns),
                display_value(row.stddev_ns),
                grouped(row.ops_per_sec),
                row.samples,
                row.inner
            );
        }
    }
}

fn measure<T, F>(category: &str, name: &str, samples: usize, target_ms: f64, work: &mut F) -> Row
where
    F: FnMut() -> T,
{
    for _ in 0..3 {
        black_box(work());
    }

    let estimate_start = Instant::now();
    let estimate_reps = 10u64;
    for _ in 0..estimate_reps {
        black_box(work());
    }
    let estimate_ns = estimate_start.elapsed().as_nanos() as f64 / estimate_reps as f64;
    let target_ns = target_ms * 1_000_000.0;
    let inner = if estimate_ns <= 0.0 {
        2_000_000
    } else {
        (target_ns / estimate_ns).clamp(1.0, 2_000_000.0) as u64
    };

    let mut times = Vec::with_capacity(samples);
    for _ in 0..samples {
        let start = Instant::now();
        for _ in 0..inner {
            black_box(work());
        }
        let elapsed = start.elapsed().as_nanos() as f64 / inner as f64;
        times.push(elapsed);
    }

    let mean_ns = times.iter().sum::<f64>() / times.len() as f64;
    let mut sorted = times.clone();
    sorted.sort_by(f64::total_cmp);
    let median_ns = sorted.get(sorted.len() / 2).copied().unwrap_or(mean_ns);
    let p95_index = sorted
        .len()
        .saturating_mul(95)
        .saturating_div(100)
        .min(sorted.len().saturating_sub(1));
    let p95_ns = sorted.get(p95_index).copied().unwrap_or(median_ns);
    let min_ns = sorted.first().copied().unwrap_or(mean_ns);
    let max_ns = sorted.last().copied().unwrap_or(mean_ns);
    let variance = if times.len() > 1 {
        times
            .iter()
            .map(|value| (value - mean_ns) * (value - mean_ns))
            .sum::<f64>()
            / (times.len() - 1) as f64
    } else {
        0.0
    };
    Row {
        category: category.to_owned(),
        name: name.to_owned(),
        mean_ns,
        median_ns,
        p95_ns,
        min_ns,
        max_ns,
        stddev_ns: variance.sqrt(),
        ops_per_sec: 1_000_000_000.0 / mean_ns.max(f64::MIN_POSITIVE),
        samples,
        inner,
    }
}

fn setup_and_run(runner: &mut Runner<'_>) {
    let compact = SecretKey::from_seed(*SEED);
    let expanded = ExpandedSecretKey::from_seed(&compact);
    let public = match expanded.public_key() {
        Ok(public) => public,
        Err(_) => {
            eprintln!("KAT public key failed");
            std::process::exit(2);
        }
    };
    let (sk, pt) = api::secret_parts(&expanded);
    let constants = RainConstants::derive();
    let (_ct, witness) = rain::encrypt(sk, pt, &constants);

    let master = api::sign_master_seed(&expanded, &public, MESSAGE, &ENTROPY);
    let salt = api::sign_salt(master);
    let pk_hash = api::sign_public_key_hash(&public);
    let roots = api::sign_roots(master, salt, pk_hash);
    let (delta, chi, h2) = api::transcript_challenges(public.as_bytes(), &salt, MESSAGE, &roots);

    let mut work_sig = [0u8; SIGNATURE_LEN];
    if sign_into(MESSAGE, &expanded, &ENTROPY, &mut work_sig).is_err() {
        eprintln!("setup sign failed");
        std::process::exit(2);
    }
    let (u_values, q_values) = api::sign_openings(master, salt, pk_hash, h2, &mut work_sig);
    let (wire_w, tags) = api::sign_wires(sk, &witness, &u_values, &q_values, delta, &mut work_sig);
    let q_open = api::sign_opened_wires(EXPECTED_SIG, delta);

    let ggm_seed = [0x42u8; FIELD_BYTES];
    let (hidden, commitment, copath) = api::ggm_hidden_opening(ggm_seed, 0, 42, salt, pk_hash);
    let _ = hidden;

    // Field arithmetic. Vary inputs so the optimizer cannot hoist a
    // single constant operation out of the measurement loop.
    let mut a_values = [F288::ZERO; 256];
    let mut b_values = [F288::ZERO; 256];
    let mut byte_values = [[0u8; FIELD_BYTES]; 256];
    for index in 0usize..256 {
        let mut left = [0u8; FIELD_BYTES];
        let mut right = [0u8; FIELD_BYTES];
        for offset in 0..FIELD_BYTES {
            left[offset] = u8::try_from((index.wrapping_mul(37).wrapping_add(offset * 11)) & 0xFF)
                .unwrap_or(0);
            right[offset] =
                u8::try_from((index.wrapping_mul(53).wrapping_add(offset * 7)) & 0xFF).unwrap_or(0);
        }
        left[0] |= 1;
        a_values[index] = F288::from_bytes(left);
        b_values[index] = F288::from_bytes(right);
        byte_values[index] = left;
    }
    let mut cursor = 0usize;
    runner.run("field", "add", || {
        cursor = cursor.wrapping_add(1) & 255;
        black_box(a_values[cursor]) + black_box(b_values[cursor])
    });
    let mut cursor = 0usize;
    runner.run("field", "mul", || {
        cursor = cursor.wrapping_add(1) & 255;
        black_box(a_values[cursor]) * black_box(b_values[cursor])
    });
    let mut cursor = 0usize;
    runner.run("field", "square", || {
        cursor = cursor.wrapping_add(1) & 255;
        black_box(a_values[cursor]).square()
    });
    let mut cursor = 0usize;
    runner.run("field", "inverse", || {
        cursor = cursor.wrapping_add(1) & 255;
        black_box(a_values[cursor]).inverse()
    });
    let mut cursor = 0usize;
    runner.run("field", "from_bytes", || {
        cursor = cursor.wrapping_add(1) & 255;
        F288::from_bytes(black_box(byte_values[cursor]))
    });
    let mut cursor = 0usize;
    runner.run("field", "to_bytes", || {
        cursor = cursor.wrapping_add(1) & 255;
        black_box(a_values[cursor]).to_bytes()
    });

    // BLAKE3 / WH512.
    let empty: &[u8] = b"";
    let field_data = [0x42u8; FIELD_BYTES];
    let data64 = [0x42u8; 64];
    let data1k = vec![0x42u8; 1024];
    let data1m = vec![0x42u8; 1024 * 1024];
    runner.run("hash", "blake3.empty", || blake3::hash(black_box(empty)));
    runner.run("hash", "blake3.64B", || blake3::hash(black_box(&data64)));
    runner.run("hash", "blake3.1KiB", || blake3::hash(black_box(&data1k)));
    runner.run("hash", "blake3.1MiB", || blake3::hash(black_box(&data1m)));
    runner.run("hash", "blake3_xof.64B", || {
        let mut out = [0u8; 64];
        blake3::hash_xof(black_box(&data64), &mut out);
        out
    });
    runner.run("hash", "keyed_hash.64B", || {
        blake3::keyed_hash(black_box([0x24u8; 32]), black_box(&data64))
    });
    runner.run("hash", "derive_key.profile_field", || {
        let mut out = [0u8; FIELD_BYTES];
        blake3::derive_key("VORB3-BENCH-V1", black_box(&field_data), &mut out);
        out
    });
    runner.run("hash", "wh512.profile_field", || {
        blake3::wh512(black_box(&field_data))
    });
    runner.run("hash", "wh512.2240B", || blake3::wh512(black_box(&roots)));

    // Rain-SP1.
    runner.run("rain", "constants_derive", || {
        black_box(RainConstants::derive())
    });
    runner.run("rain", "encrypt", || {
        rain::encrypt(black_box(sk), black_box(pt), black_box(&constants))
    });

    // GGM / Merkle.
    runner.run("ggm", "tree_root.1", || {
        api::ggm_tree_root(ggm_seed, 0, salt, pk_hash)
    });
    runner.run("ggm", "hidden_opening.1", || {
        api::ggm_hidden_opening(ggm_seed, 0, 42, salt, pk_hash)
    });
    runner.run("ggm", "reconstruct_root.1", || {
        api::ggm_reconstruct_root(commitment, copath, 0, 42, salt, pk_hash)
    });
    runner.run("ggm", "roots.35", || api::sign_roots(master, salt, pk_hash));
    runner.run("ggm", "openings.35", || {
        api::sign_openings(master, salt, pk_hash, h2, &mut work_sig)
    });
    runner.run("ggm", "reconstruct_roots.35", || {
        api::sign_reconstruct_roots(EXPECTED_SIG, salt, pk_hash, h2)
    });

    // Transcript and sign phases.
    runner.run("transcript", "challenges.32B", || {
        api::transcript_challenges(public.as_bytes(), &salt, MESSAGE, &roots)
    });
    let message1m = vec![0x5Au8; 1024 * 1024];
    runner.run("transcript", "challenges.1MiB", || {
        api::transcript_challenges(public.as_bytes(), &salt, &message1m, &roots)
    });
    runner.run("sign-phase", "master_seed.32B", || {
        api::sign_master_seed(&expanded, &public, MESSAGE, &ENTROPY)
    });
    runner.run("sign-phase", "master_seed.1MiB", || {
        api::sign_master_seed(&expanded, &public, &message1m, &ENTROPY)
    });
    runner.run("sign-phase", "salt", || api::sign_salt(master));
    runner.run("sign-phase", "pk_hash", || {
        api::sign_public_key_hash(&public)
    });
    runner.run("sign-phase", "wires.31", || {
        api::sign_wires(sk, &witness, &u_values, &q_values, delta, &mut work_sig)
    });
    runner.run("quicksilver", "prove.60gates", || {
        api::sign_prove(&witness, &wire_w, &tags, chi, &constants)
    });
    runner.run("quicksilver", "opened_wires.31", || {
        api::sign_opened_wires(EXPECTED_SIG, delta)
    });
    runner.run("quicksilver", "check_proof.60gates", || {
        api::sign_check_proof(&public, EXPECTED_SIG, delta, chi, &q_open, &constants)
    });

    // Keys and parsing.
    runner.run("keys", "secret_key_wrap", || {
        SecretKey::from_seed(black_box(*SEED))
    });
    runner.run("keys", "expand", || ExpandedSecretKey::from_seed(&compact));
    runner.run("keys", "public_key", || expanded.public_key());
    runner.run("keys", "keygen_full", || {
        let compact = SecretKey::from_seed(*SEED);
        let expanded = ExpandedSecretKey::from_seed(&compact);
        expanded.public_key()
    });
    runner.run("parse", "public_key.profile", || {
        PublicKey::from_bytes(black_box(*EXPECTED_PK))
    });
    runner.run("parse", "signature.profile", || {
        Signature::from_bytes(black_box(EXPECTED_SIG))
    });

    // Full sign/verify at several message sizes.
    let sizes = [
        (0usize, "0B"),
        (32, "32B"),
        (1024, "1KiB"),
        (65_536, "64KiB"),
        (1_048_576, "1MiB"),
        (16_777_216, "16MiB"),
    ];
    for (length, label) in sizes {
        let message = vec![0x5Au8; length];
        let mut signature = [0u8; SIGNATURE_LEN];
        if sign_into(&message, &expanded, &ENTROPY, &mut signature).is_err() {
            eprintln!("size setup sign failed at {label}");
            std::process::exit(2);
        }
        runner.run("full", &format!("sign.{label}"), || {
            sign_into(&message, &expanded, &ENTROPY, &mut signature)
        });
        runner.run("full", &format!("verify.{label}"), || {
            verify_bytes(&message, &public, &signature)
        });
    }

    // Convenience wrappers and combined end-to-end.
    let expected_signature = match Signature::from_bytes(EXPECTED_SIG) {
        Ok(signature) => signature,
        Err(_) => {
            eprintln!("KAT signature parse failed");
            std::process::exit(2);
        }
    };
    runner.run("full", "sign_wrapper.32B", || {
        sign(MESSAGE, &expanded, &ENTROPY)
    });
    runner.run("full", "verify_wrapper.32B", || {
        verify(MESSAGE, &public, &expected_signature)
    });
    runner.run("full", "sign_verify.32B", || {
        let mut signature = [0u8; SIGNATURE_LEN];
        let signed = sign_into(MESSAGE, &expanded, &ENTROPY, &mut signature);
        let verified = verify_bytes(MESSAGE, &public, &signature);
        (signed, verified)
    });
}

fn display_value(value: f64) -> String {
    if value < 10.0 {
        format!("{value:.2}")
    } else if value < 100.0 {
        format!("{value:.1}")
    } else {
        grouped(value)
    }
}

fn grouped(value: f64) -> String {
    let negative = value < 0.0;
    let digits = value.abs().round().to_string();
    let mut out = String::with_capacity(digits.len() + digits.len() / 3 + 1);
    if negative {
        out.push('-');
    }
    for (index, byte) in digits.bytes().enumerate() {
        if index > 0 && (digits.len() - index).is_multiple_of(3) {
            out.push(',');
        }
        out.push(char::from(byte));
    }
    out
}

fn cpu_model() -> String {
    let Ok(cpuinfo) = std::fs::read_to_string("/proc/cpuinfo") else {
        return "unknown".to_owned();
    };
    for line in cpuinfo.lines() {
        if let Some(value) = line.strip_prefix("model name")
            && let Some((_, model)) = value.split_once(':')
        {
            return model.trim().to_owned();
        }
    }
    "unknown".to_owned()
}

fn max_rss_kb() -> u64 {
    let Ok(status) = std::fs::read_to_string("/proc/self/status") else {
        return 0;
    };
    for line in status.lines() {
        if let Some(value) = line.strip_prefix("VmHWM:")
            && let Some(number) = value.split_whitespace().next()
        {
            return number.parse::<u64>().unwrap_or(0);
        }
    }
    0
}
