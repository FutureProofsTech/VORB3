//! Full local benchmark suite for VORB3 SP-288/35.
//!
//! This is a measurement tool, not a demo. It uses std only, no third-party
//! crates, and the `bench-api` feature for private protocol phases. Results
//! are machine- and compiler-dependent evidence, not a security proof.

use std::hint::black_box;
use std::time::Instant;

