#[test]
fn blake3_hashes() {
    assert_eq!(hash(b""), HASH_EMPTY);
    assert_eq!(hash(b"abc"), HASH_ABC);
    assert_eq!(hash(&[0u8; 1024]), HASH_ZERO1024);

    let mut pattern = [0u8; 3000];
    for (index, byte) in pattern.iter_mut().enumerate() {
        *byte = u8::try_from(index.wrapping_mul(37).wrapping_add(11) & 0xFF).unwrap_or(0);
    }
    assert_eq!(hash(&pattern), HASH_PATTERN3000);
}

#[test]
fn blake3_xof_keyed_derive() {
    let mut xof = [0u8; 64];
    hash_xof(b"", &mut xof);
    assert_eq!(xof, XOF64_EMPTY);

    let mut key = [0u8; 32];
    for (index, byte) in key.iter_mut().enumerate() {
        *byte = u8::try_from(index).unwrap_or(0);
    }
    assert_eq!(keyed_hash(key, b"abc"), KEYED_ABC);

    let mut derived = [0u8; 32];
    derive_key("VORB3-TEST-V1", b"abc", &mut derived);
    assert_eq!(derived, DERIVE_ABC);
}

#[test]
fn xof_prefix_property() {
    let mut short = [0u8; 32];
    derive_key("VORB3-GGM-EXPAND-V1", b"length-check", &mut short);
    let mut long = [0u8; 72];
    derive_key("VORB3-GGM-EXPAND-V1", b"length-check", &mut long);
    for (long_byte, short_byte) in long.iter().take(32).zip(short.iter()) {
        assert_eq!(long_byte, short_byte);
    }

    let mut xof = [0u8; 131];
    hash_xof(b"abc", &mut xof);
    for (xof_byte, hash_byte) in xof.iter().take(32).zip(HASH_ABC.iter()) {
        assert_eq!(xof_byte, hash_byte);
    }
}

#[test]
fn wh512_vectors() {
    assert_eq!(wh512(b"abc"), WH512_ABC);
    assert_eq!(wh512(b""), WH512_EMPTY);
}
