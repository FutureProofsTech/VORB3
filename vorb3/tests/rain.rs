//! Rain-SP1 known-answer test against the independent Python model.
#![allow(clippy::arithmetic_side_effects)] // field operators are total; no integer overflow.

use vorb3::field::F288;
use vorb3::rain::{RainConstants, encrypt};

const SK: [u8; 36] = [
    0x03, 0x0a, 0x11, 0x18, 0x1f, 0x26, 0x2d, 0x34, 0x3b, 0x42, 0x49, 0x50, 0x57, 0x5e, 0x65, 0x6c,
    0x73, 0x7a, 0x81, 0x88, 0x8f, 0x96, 0x9d, 0xa4, 0xab, 0xb2, 0xb9, 0xc0, 0xc7, 0xce, 0xd5, 0xdc,
    0xe3, 0xea, 0xf1, 0xf8,
];

const PT: [u8; 36] = [
    0x05, 0x10, 0x1b, 0x26, 0x31, 0x3c, 0x47, 0x52, 0x5d, 0x68, 0x73, 0x7e, 0x89, 0x94, 0x9f, 0xaa,
    0xb5, 0xc0, 0xcb, 0xd6, 0xe1, 0xec, 0xf7, 0x02, 0x0d, 0x18, 0x23, 0x2e, 0x39, 0x44, 0x4f, 0x5a,
    0x65, 0x70, 0x7b, 0x86,
];

const CT: [u8; 36] = [
    0xea, 0xfb, 0xad, 0xce, 0x3a, 0x55, 0xa2, 0x07, 0x2e, 0x14, 0x51, 0xa8, 0xaf, 0x36, 0xc5, 0x92,
    0x12, 0xa4, 0xa9, 0xe4, 0xa3, 0x3e, 0x4c, 0x95, 0xad, 0x5f, 0xc3, 0x07, 0xac, 0x56, 0x74, 0x42,
    0x86, 0x37, 0x65, 0x82,
];

#[test]
fn rain_sp1_kat() {
    let constants = RainConstants::derive();
    let sk = F288::from_bytes(SK);
    let pt = F288::from_bytes(PT);
    let (ct, _witness) = encrypt(sk, pt, &constants);
    assert_eq!(ct, F288::from_bytes(CT));

    let other = F288::from_bytes(PT);
    let (other_ct, _) = encrypt(sk + F288::ONE, other, &constants);
    assert_ne!(other_ct, ct);
}
